def engine_worker(conn, cancelled, body):
    from p006_app import workflow_service as service
    from p006_app.workflow_state import SourceIdentity
    from p006_converter import core
    try:
        conn.send({"phase": "SOURCE_READING", "label": "원본 파일과 SHA 확인 중"})
        path = Path(body["path"])
        core._reject_link_like_ancestors(path, "source")
        identity = SourceIdentity.from_file(path)
        if cancelled.is_set():
            raise core.ConversionCancelled("cancelled")
        request, profile = request_for(path, body["cpu"], body["mode"], identity, body.get("statement_policy", "in_plc"))
        conn.send({"phase": "ANALYZING", "label": "기존 엔진에서 POU 분석 중", "source_identity": asdict(identity)})
        analysis = service.analyze(request, cancelled.is_set)
        if analysis.source_identity != identity:
            raise ValueError("원본을 읽을 수 없거나 내용이 변경되었습니다. 진단을 확인하고 다시 선택하세요. " +
                             "; ".join(f"{d.code}: {d.reason} {d.detail}" for d in analysis.diagnostics))
        conn.send({"phase": "PLANNING", "label": f"{len(analysis.programs)}개 POU 분석 후 CPU와 주소 계획 점검 중"})
        plan = service.plan(request, cancelled.is_set)
        if cancelled.is_set():
            raise core.ConversionCancelled("cancelled")
        if plan.analysis.source_identity != identity or SourceIdentity.from_file(path) != identity:
            raise ValueError("계획 중 원본 내용이 변경되었습니다. 이전 계획을 무효화하고 다시 선택하세요.")
        conn.send({"phase": "COMPLETE", "label": "분석과 계획 완료 (파일 발행 안 함)", "result": present(plan, profile)})
    except core.ConversionCancelled:
        conn.send({"phase": "CANCELLED", "label": "취소됨. 원본과 기존 결과는 보존됩니다."})
    except Exception as error:
        conn.send({"phase": "FAILED", "label": "원본 또는 설정을 확인한 뒤 다시 시도하세요.",
                   "error": {"code": type(error).__name__, "message": str(error)}})
    finally:
        conn.close()


def run_worker(worker, conn, cancelled, body, scratch):
    # Every engine-created temporary snapshot stays under this job-owned root.
    # Parent removes it only after the owned child is reaped, including forced exit.
    os.environ["TEMP"] = os.environ["TMP"] = scratch
    tempfile.tempdir = scratch
    worker(conn, cancelled, body)


class Session:
    def __init__(self, worker=engine_worker):
        self.ctx = mp.get_context("spawn")
        self.worker = worker
        self.lock = threading.RLock()
        self.mutation_lock = threading.Lock()
        self.generation = 0
        self.request_id = None
        self.version = 0
        self.events = []
        self.result = None
        self.active = None
        self.retired = []
        self.closed = False
        self.last_seen = time.monotonic()
        self.last_identity_check = 0.0

    def envelope(self):
        with self.lock:
            return {"protocol": PROTOCOL, "generation": self.generation, "request_id": self.request_id,
                    "version": self.version, "events": list(self.events), "result": self.result,
                    "busy": self.active is not None, "closed": self.closed}

    def _stop(self):
        with self.lock:
            job = self.active
            self.active = None
            jobs = ([job] if job else []) + self.retired
            self.retired = []
        for index, job in enumerate(jobs):
            try:
                self._reap(job)
            except Exception as error:
                # Preserve ownership and disable automatic directory finalization
                # if the owned process/thread cannot be confirmed stopped.
                for pending in jobs[index:]:
                    pending[4]._finalizer.detach()
                with self.lock:
                    self.retired.extend(jobs[index:])
                raise RuntimeError(f"engine cleanup failed; owned scratch preserved: {job[4].name}") from error

    def _reap(self, job):
        if job:
            proc, cancel, conn, thread, scratch = job
            cancel.set()
            # Collector drains Pipe while child exits; no Queue feeder join deadlock.
            if thread is not None and thread.ident is not None:
                thread.join(1.5)
            if proc.is_alive():
                proc.terminate()
            if thread is not None and thread.ident is not None:
                thread.join(1.5)
            proc.join(1.5)
            if proc.is_alive():
                proc.kill()
                proc.join(1.5)
            conn.close()
            if thread is not None and thread.ident is not None:
                thread.join(1.5)
            if (thread is not None and thread.is_alive()) or proc.is_alive():
                raise RuntimeError("owned engine did not stop; scratch preserved")
            scratch.cleanup()
            # Keep a usable process handle when directory deletion needs a retry.
            proc.close()

    def invalidate(self, generation, request_id, label="입력이 바뀌어 이전 계획과 확인을 무효화했습니다."):
        with self.mutation_lock:
            with self.lock:
                if self.closed or generation <= self.generation:
                    raise ValueError("STALE_GENERATION")
                self.generation, self.request_id = generation, request_id
                self.result, self.events = None, [{"phase": "INVALIDATED", "label": label}]
                self.version += 1
            self._stop()
        return self.envelope()

    def prepare(self, body):
        with self.mutation_lock:
            with self.lock:
                if self.closed or body["generation"] <= self.generation:
                    raise ValueError("STALE_GENERATION_OR_DUPLICATE")
                self.generation, self.request_id = body["generation"], body["request_id"]
                self.result, self.events = None, []
                self.version += 1
            self._stop()
            parent, child = self.ctx.Pipe(duplex=False)
            cancel = self.ctx.Event()
            scratch = tempfile.TemporaryDirectory(prefix="p006-p0-job-")
            proc = self.ctx.Process(target=run_worker, args=(self.worker, child, cancel, body, scratch.name))
            try:
                proc.start()
            except Exception as error:
                child.close(); parent.close(); proc.close(); scratch.cleanup()
                with self.lock:
                    self.events.append({"phase": "FAILED", "label": "엔진을 시작하지 못했습니다. 환경을 확인하고 다시 시도하세요.",
                                        "error": {"code": "ENGINE_START", "message": str(error)}})
                    self.version += 1
                return self.envelope()
            child.close()
            thread = None
            with self.lock:
                self.active = (proc, cancel, parent, thread, scratch)
            try:
                thread = threading.Thread(target=self._collect, args=(proc, parent, body), daemon=True)
                with self.lock:
                    self.active = (proc, cancel, parent, thread, scratch)
                thread.start()
            except Exception as error:
                self._stop()
                with self.lock:
                    self.events.append({"phase": "FAILED", "label": "진행 수집을 시작하지 못했습니다. 다시 시도하세요.",
                                        "error": {"code": "COLLECTOR_START", "message": str(error)}})
                    self.version += 1
        return self.envelope()

    def _collect(self, proc, conn, body):
        terminal = False
        try:
            while True:
                try:
                    available = conn.poll(0.1)
                except (EOFError, OSError):
                    break
                if available:
                    try:
                        event = conn.recv()
                    except (EOFError, OSError):
                        break
                    with self.lock:
                        if self.generation == body["generation"] and self.request_id == body["request_id"] and not self.closed:
                            self.events.append({k: v for k, v in event.items() if k != "result"})
                            if "result" in event:
                                self.result = event["result"]
                            self.version += 1
                    terminal = event["phase"] in {"COMPLETE", "FAILED", "CANCELLED"}
                    if terminal:
                        break
                elif not proc.is_alive():
                    break
        finally:
            proc.join(1)
            with self.lock:
                if self.generation == body["generation"] and self.request_id == body["request_id"] and not self.closed:
                    if not terminal:
                        self.events.append({"phase": "FAILED", "label": "엔진이 중단되었습니다. 원본을 확인하고 다시 시도하세요.",
                                            "error": {"code": "ENGINE_EXIT", "message": f"exitcode={proc.exitcode}"}})
                        self.result = None
                    # Keep handles until next mutation/close so every process is reaped/closed.
                    self.version += 1

    def snapshot(self):
        from p006_app.workflow_state import SourceIdentity
        with self.lock:
            identity = (self.result or {}).get("source_identity")
            generation = self.generation
            check = identity is not None and time.monotonic() - self.last_identity_check > 2
            if check:
                self.last_identity_check = time.monotonic()
        if check:
            try:
                unchanged = asdict(SourceIdentity.from_file(identity["path"])) == identity
            except (ValueError, OSError):
                unchanged = False
            if not unchanged:
                with self.lock:
                    if self.generation == generation and self.result is not None:
                        self.result = None
                        self.events.append({"phase": "INVALIDATED", "label": "원본 내용이 바뀌어 계획과 승인 표시를 무효화했습니다. 다시 분석하세요."})
                        self.version += 1
        with self.lock:
            self.last_seen = time.monotonic()
            snapshot = self.envelope()
            if self.active:
                snapshot["busy"] = self.active[3] is not None and self.active[3].is_alive()
                snapshot["worker_pid"] = self.active[0].pid
            return snapshot

    def close(self):
        with self.mutation_lock:
            with self.lock:
                self.closed = True
                self.generation += 1
                self.result = None
                self.version += 1
            self._stop()
