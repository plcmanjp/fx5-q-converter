def request_for(path, cpu, mode, identity, statement_policy="in_plc"):
    from p006_app import workflow_service as service
    from p006_app.approved_profiles import load_approved_profile
    from p006_app.unified_app import suggest_direction
    from p006_converter.fx5_target import validate_cpu
    direction = suggest_direction(path)
    if direction is None:
        raise ValueError("지원 형식은 .gx3 및 .gxw입니다. 파일 선택으로 원본을 다시 선택하세요.")
    validate_cpu(cpu)
    if mode not in {"convert", "source_review"} or (mode == "source_review" and direction != service.Q_TO_FX5):
        raise ValueError("Q 원본 대조는 .gxw에서만 사용할 수 있습니다.")
    options = {"q_source_review": True} if mode == "source_review" else {"complete_text": True}
    if mode == "convert":
        options["statement_policy"] = statement_policy
    settings = relocation = None
    profile_id = None
    if mode == "convert" and direction == service.Q_TO_FX5:
        options["target_cpu"] = cpu
        profile = load_approved_profile(identity.sha256, direction, cpu)
        if profile is not None:
            settings, relocation = profile.settings, profile.relocation_settings
            profile_id = profile.profile_id
            options.update(settings_source_path=profile.settings_source_path,
                           settings_source_sha256=profile.settings_source_sha256,
                           relocation_settings_source_path=profile.relocation_settings_source_path,
                           relocation_settings_source_sha256=profile.relocation_settings_source_sha256)
    return service.WorkflowRequest(direction, path, settings=settings,
                                   relocation_settings=relocation, options=options), profile_id


